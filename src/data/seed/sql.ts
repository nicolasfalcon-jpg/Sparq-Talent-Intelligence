/**
 * Builds supabase/seed.sql from the FICTIONAL fixtures, so the database and the in-memory adapter share one dataset.
 * Pure: returns a string. `npm run db:seed:generate` writes it; a test fails if the committed file is stale.
 *
 * REPEATABLE: every statement is `on conflict do nothing` (or `where not exists` for audit rows), so running the seed twice leaves the
 * same rows and never overwrites changes. To reset a local database use `supabase db reset`.
 * It runs as the database owner, which is what lets it insert already-verified evidence and confirmed assignments: those are
 * things application roles can never do.
 *
 * What the fixtures do not contain and the database needs is INVENTED and fictional: verification dates (2026-11-12 unless a fixture
 * says a year or month), assignment start dates (2025-01-06), the submission date of the Vela proposal, and the extra identities
 * in ids.ts. Everything else is the fixture dataset: 12 profiles, 67 evidence rows, projects, opportunities and roles, availability,
 * shared-versus-private interests and the Vela proposal with its two proposed people.
 */
import { capabilities } from "../fixtures/capabilities";
import { DEMO_TODAY, opportunities } from "../fixtures/organization";
import { availability, careerInterests, evidence, people, projects } from "../fixtures/people";
import { SEED_USERS, seedId, userId, type SeedUserKey } from "./ids";

const q = (v: string | number | boolean | null | undefined): string =>
  v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : typeof v === "boolean" ? String(v) : `'${v.replace(/'/g, "''")}'`;
const arr = (a: readonly string[]): string => `array[${a.map(q).join(", ")}]::text[]`;
const ts = (d: string): string => `${q(d)}::timestamptz`;
const uid = (v: string | null): string => (v === null ? "null::uuid" : `${q(v)}::uuid`);

const userByName = (name: string): string => {
  const hit = SEED_USERS.find((u) => u.name === name.split(",")[0]!.trim());
  if (!hit) throw new Error(`No seed user named "${name}"`);
  return userId(hit.key as SeedUserKey);
};

/** Partial dates in the fixtures ("2026-11", "2024") become full timestamps; a missing date becomes the seed's review day. */
const SEED_REVIEW_DAY = "2026-11-12T12:00:00Z";
function stamp(partial: string | undefined): string {
  if (!partial) return SEED_REVIEW_DAY;
  if (/^\d{4}$/.test(partial)) return `${partial}-06-30T12:00:00Z`;
  if (/^\d{4}-\d{2}$/.test(partial)) return `${partial}-12T12:00:00Z`;
  return `${partial}T12:00:00Z`;
}

export function buildSeedSql(): string {
  const out: string[] = [];
  const add = (...lines: string[]) => out.push(...lines);
  const insert = (table: string, columns: string[], rows: string[]) => {
    if (rows.length === 0) return;
    add(`insert into ${table} (${columns.join(", ")}) values`, rows.map((r) => `  (${r})`).join(",\n"), "on conflict do nothing;", "");
  };

  add(
    "-- GENERATED by `npm run db:seed:generate` from src/data/fixtures. DO NOT EDIT BY HAND.",
    "-- FICTIONAL DATA ONLY: no real employee, client or project. Repeatable (idempotent). Runs as the database owner.",
    `-- The fixed demo day of the dataset is ${DEMO_TODAY}.`,
    "begin;",
    "",
  );

  // ---- identities -------------------------------------------------------------------------------------------------
  // The accounts themselves are created by Supabase Auth (scripts/db/provision.mjs). The seed only attaches application rows to them,
  // and refuses to run, with a clear message, when an account is missing: a seed must never invent authentication identities.
  add(
    "do $$",
    "declare missing text;",
    "begin",
    `  select string_agg(v.k, ', ') into missing from (values ${SEED_USERS.map((u) => `(${q(u.key)}, ${q(userId(u.key))}::uuid)`).join(", ")}) as v(k, id)`,
    "    where not exists (select 1 from auth.users a where a.id = v.id);",
    "  if missing is not null then",
    "    raise exception 'seed: demo account(s) missing from auth.users: %. Provision them first (npm run db:provision), then seed again.', missing using errcode = '23503';",
    "  end if;",
    "end $$;",
    "",
  );

  // ---- reference data and profiles --------------------------------------------------------------------------------
  insert("public.capabilities", ["id", "slug", "name", "grp", "aliases"], capabilities.map((c) => `${q(seedId("capability", c.id))}, ${q(c.id)}, ${q(c.name)}, ${q(c.group)}, ${arr(c.aliases)}`));
  insert("public.people",
    ["id", "slug", "name", "headline", "discipline", "location", "country", "years_experience", "at_sparq_since", "languages", "summary", "top_skills", "passport_groups"],
    people.map((p) => [
      q(seedId("person", p.id)), q(p.id), q(p.name), q(p.headline), q(p.discipline), q(p.location), q(p.country ?? null), p.yearsExperience, q(p.atSparqSince ?? null),
      arr(p.languages), q(p.summary), arr(p.topSkills), p.passportGroups ? `${q(JSON.stringify(p.passportGroups))}::jsonb` : "null",
    ].join(", ")));
  insert("public.app_users", ["id", "display_name", "title", "person_id"], SEED_USERS.map((u) => `${q(userId(u.key))}, ${q(u.name)}, ${q(u.title)}, ${u.person ? q(seedId("person", u.person)) : "null"}`));

  const admin = userId("admin");
  insert("public.user_roles", ["user_id", "role", "granted_by"], SEED_USERS.flatMap((u) => u.roles.map((r) => `${q(userId(u.key))}, ${q(r)}, ${r === "admin" ? "null" : q(admin)}`)));

  insert("public.person_preferences", ["person_id", "work_preferences", "shared_with_staffing"],
    people.filter((p) => p.workPreferences).map((p) => `${q(seedId("person", p.id))}, ${q(p.workPreferences!)}, ${p.workPreferencesShared === true}`));
  insert("public.career_journey_entries", ["person_id", "position", "period_label", "role", "org", "is_current"],
    people.flatMap((p) => p.journey.map((j, i) => `${q(seedId("person", p.id))}, ${i}, ${q(j.when)}, ${q(j.role)}, ${q(j.org)}, ${j.current}`)));
  insert("public.certifications", ["id", "person_id", "name", "issued_label", "position"],
    people.flatMap((p) => p.certifications.map((c, i) => `${q(seedId("evidence", `${p.id}-cert-${i}`))}, ${q(seedId("person", p.id))}, ${q(c.name)}, ${q(c.date)}, ${i}`)));

  // ---- evidence and experience (source and verification are separate; verification carries who and when) ---------------
  const leadOf = (personId: string): string => {
    const name = availability.find((a) => a.personId === personId)?.deliveryLead;
    return name ? userByName(name) : userId("rafael");
  };
  insert("public.skill_evidence",
    ["id", "person_id", "capability_id", "label", "source", "detail", "verification", "verified_by", "verified_at", "verification_note"],
    evidence.map((e) => {
      const verified = e.verification === "verified";
      return [
        q(seedId("evidence", e.id)), q(seedId("person", e.personId)), q(seedId("capability", e.capabilityId)), q(e.label), q(e.level), q(e.detail), q(e.verification),
        verified ? q(leadOf(e.personId)) : "null", verified ? ts(stamp(e.verifiedOn)) : "null", verified ? q(e.verifiedBy ?? null) : "null",
      ].join(", ");
    }));
  insert("public.project_experience",
    ["id", "person_id", "sort_order", "period_label", "client", "client_category", "role", "title", "summary", "tags", "highlights", "verification", "verified_by", "verified_at"],
    people.flatMap((person) => projects.filter((p) => p.personId === person.id).map((p, i) => {
      const verified = p.verification === "verified";
      return [
        q(seedId("project", p.id)), q(seedId("person", p.personId)), i, q(p.period), q(p.client), q(p.clientCategory ?? null), q(p.role), q(p.title), q(p.summary),
        arr(p.tags), arr(p.highlights), q(p.verification), verified ? q(userByName(p.verifiedBy ?? "")) : "null", verified ? ts(stamp(p.verifiedOn)) : "null",
      ].join(", ");
    })));

  // ---- interests: private by default, shared only what the fixtures say the person shared ---------------------------
  insert("public.career_interests", ["person_id", "interest", "selected", "shared_with_staffing"],
    careerInterests.flatMap((c) => Object.entries(c.interests).map(([label, selected]) => `${q(seedId("person", c.personId))}, ${q(label)}, ${selected}, ${selected && c.shared.includes(label)}`)));

  // ---- opportunities, roles, project-level reviewers ----------------------------------------------------------------
  insert("public.opportunities", ["id", "slug", "client", "client_initials", "industry", "name", "short", "description", "status", "kickoff", "duration_months", "capabilities", "created_by"],
    opportunities.map((o) => `${q(seedId("opportunity", o.id))}, ${q(o.id)}, ${q(o.client)}, ${q(o.clientInitials)}, ${q(o.industry)}, ${q(o.name)}, ${q(o.short)}, ${q(o.description)}, ${q(o.status)}, ${q(o.kickoff)}, ${o.durationMonths}, ${arr(o.capabilities)}, ${q(userId("laura"))}`));
  insert("public.role_requirements", ["id", "slug", "opportunity_id", "sort_order", "title", "capabilities"],
    opportunities.flatMap((o) => o.roles.map((r, i) => `${q(seedId("role", r.id))}, ${q(r.id)}, ${q(seedId("opportunity", o.id))}, ${i}, ${q(r.title)}, ${arr(r.capabilities)}`)));
  insert("public.opportunity_delivery_leads", ["opportunity_id", "user_id", "granted_by"],
    opportunities.map((o) => `${q(seedId("opportunity", o.id))}, ${q(userByName(o.deliveryLead))}, ${q(admin)}`));

  // ---- availability inputs: current work as CONFIRMED assignments (availability itself is derived) ---------------------
  insert("public.assignments", ["id", "person_id", "project_name", "starts_on", "ends_on", "available_from", "allocation", "end_confirmed", "delivery_lead_id", "confirmed_by", "confirmed_at"],
    availability.filter((a) => a.currentProject).map((a) => {
      const lead = userByName(a.deliveryLead ?? "Rafael Ortiz");
      return `${q(seedId("assignment", a.personId))}, ${q(seedId("person", a.personId))}, ${q(a.currentProject!)}, '2025-01-06', ${q(a.currentProjectEnds)}, ${q(a.availableFrom)}, 1, ${a.status === "confirmed"}, ${q(lead)}, ${q(lead)}, ${ts("2026-11-01T09:00:00Z")}`;
    }));

  // ---- proposals: a PROPOSED person is not an assignment ----------------------------------------------------------
  const withProposals = opportunities.filter((o) => o.roles.some((r) => r.proposedPersonId));
  insert("public.team_proposals", ["id", "opportunity_id", "title", "state", "version", "created_by", "submitted_by", "submitted_at"],
    withProposals.map((o) => `${q(seedId("proposal", o.id))}, ${q(seedId("opportunity", o.id))}, ${q(`${o.client} · ${o.name}`)}, 'submitted', 1, ${q(userId("laura"))}, ${q(userId("laura"))}, ${ts("2026-11-20T10:00:00Z")}`));
  insert("public.proposal_seats", ["id", "proposal_id", "role_requirement_id", "position", "title", "capabilities", "allocation", "person_id", "seat_state"],
    withProposals.flatMap((o) => o.roles.map((r, i) => `${q(seedId("seat", r.id))}, ${q(seedId("proposal", o.id))}, ${q(seedId("role", r.id))}, ${i}, ${q(r.title)}, ${arr(r.capabilities)}, 1, ${r.proposedPersonId ? q(seedId("person", r.proposedPersonId)) : "null"}, ${r.proposedPersonId ? "'proposed'" : "'open'"}`)));

  // ---- expression of interest in a SPECIFIC role (separate from private career interests) --------------------------
  insert("public.expressions_of_interest", ["id", "person_id", "role_requirement_id", "status", "note"],
    [`${q(seedId("interest", "ana-vela-mobile"))}, ${q(seedId("person", "ana"))}, ${q(seedId("role", "vela-mobile"))}, 'shared', 'Interested in the mobile role'`]);

  // ---- audit history consistent with the seeded state (idempotent) -----------------------------------------------------
  const audit: string[] = [];
  const row = (at: string, actor: string, action: string, type: string, subject: string, person: string | null, details: Record<string, unknown>) =>
    audit.push([ts(at), `${q(actor)}::uuid`, q(action), q(type), `${q(subject)}::uuid`, uid(person), `${q(JSON.stringify({ ...details, seeded: true }))}::jsonb`].join(", "));
  for (const e of evidence.filter((x) => x.verification === "verified")) row(stamp(e.verifiedOn), leadOf(e.personId), "evidence.verify", "skill_evidence", seedId("evidence", e.id), seedId("person", e.personId), { label: e.label, from: "self_reported", to: "verified" });
  for (const p of projects.filter((x) => x.verification === "verified")) row(stamp(p.verifiedOn), userByName(p.verifiedBy ?? ""), "evidence.verify", "project_experience", seedId("project", p.id), seedId("person", p.personId), { label: p.title, from: "self_reported", to: "verified" });
  for (const u of SEED_USERS) for (const r of u.roles) if (r !== "admin") row("2026-10-01T09:00:00Z", admin, "permission.grant", "app_user", userId(u.key), null, { role: r });
  for (const o of opportunities) row("2026-10-01T09:05:00Z", admin, "permission.assign_delivery_lead", "opportunity", seedId("opportunity", o.id), null, { user_id: userByName(o.deliveryLead), assigned: true });
  for (const o of withProposals) row("2026-11-20T10:00:00Z", userId("laura"), "proposal.submit", "team_proposal", seedId("proposal", o.id), null, { opportunity_id: seedId("opportunity", o.id), version: 1 });
  for (const a of availability.filter((x) => x.currentProject)) row("2026-11-01T09:00:00Z", userByName(a.deliveryLead ?? "Rafael Ortiz"), "assignment.confirm", "assignment", seedId("assignment", a.personId), seedId("person", a.personId), { project: a.currentProject });
  add(
    "insert into public.audit_log (occurred_at, actor_id, action, subject_type, subject_id, subject_person_id, details)",
    "select v.* from (values",
    audit.map((r) => `  (${r})`).join(",\n"),
    ") as v(occurred_at, actor_id, action, subject_type, subject_id, subject_person_id, details)",
    "where not exists (",
    "  select 1 from public.audit_log a where a.action = v.action and a.subject_id = v.subject_id and a.actor_id = v.actor_id and a.details ->> 'seeded' = 'true'",
    ");",
    "",
    "commit;",
    "",
  );
  return out.join("\n");
}
